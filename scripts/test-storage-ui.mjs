import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createServer } from '../src/server.mjs';
import { Service } from '../src/core/service.mjs';

const root = path.resolve('artifacts/ui-storage');
fs.mkdirSync(root, { recursive: true });
const base = fs.mkdtempSync(path.join(root, 'case-')), anchor = path.join(base, 'original'), target = path.join(base, '迁移目标');
let picked = null, pickerError = null, pickerCalls = 0;
const chooseDirectory = async () => { pickerCalls++; if (pickerError) throw new Error(pickerError); return picked; };
let app = await createServer({ directory: anchor, port: 0, chooseDirectory }), browser;
const errors = [];
try {
  const library = app.service.store.saveLibrary({ title: '我的知识库' });
  const note = app.service.store.write({ type: 'note', data: { title: '存储位置测试', content: '保留正文', domain: library.id } });
  try { browser = await chromium.launch({ headless: true }); }
  catch { browser = await chromium.launch({ channel: 'msedge', headless: true }); }
  const page = await browser.newPage({ viewport: { width: 1165, height: 892 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(app.url);
  await page.locator('[data-nav="settings"]').click();
  assert.equal(await page.locator('#storage-current').inputValue(), anchor);
  assert.equal(await page.locator('[data-mode="select"]').isVisible(), true);
  assert.equal(await page.locator('[data-mode="migrate"]').isVisible(), true);
  assert.equal(await page.locator('[data-mode="open"]').isVisible(), true);
  for (const [width, height] of [[1480, 940], [1165, 892], [600, 900]]) {
    await page.setViewportSize({ width, height });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(root, `settings-${width}.png`), fullPage: true });
    await page.locator('#agent-preferences-form button').scrollIntoViewIfNeeded();
    const bounds = await page.locator('#agent-preferences-form button').boundingBox();
    assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= height);
    assert.ok((await page.locator('.statusbar').boundingBox()).y < height);
    await page.locator('#storage-settings').scrollIntoViewIfNeeded();
  }
  await page.setViewportSize({ width: 1165, height: 892 });
  await page.locator('[data-mode="select"]').click();
  await page.waitForFunction(() => !document.querySelector('#modal').open);
  assert.equal(app.service.storage.status().pending, null);
  pickerError = '无法完成文件夹选择';
  await page.locator('[data-mode="open"]').click();
  await page.locator('#toast', { hasText: pickerError }).waitFor();
  pickerError = null;
  assert.equal(await page.locator('#modal').isVisible(), false);
  await page.locator('#agent-preferences-form textarea').fill('尚未保存的偏好');
  await page.locator('[data-mode="migrate"]').click();
  await page.locator('#toast', { hasText: '请先保存整理偏好' }).waitFor();
  assert.equal(await page.locator('#modal').isVisible(), false);
  await page.locator('#agent-preferences-form textarea').fill('');
  picked = anchor;
  await page.locator('[data-mode="migrate"]').click();
  await page.locator('#storage-target').waitFor();
  assert.equal(await page.locator('#storage-target').inputValue(), anchor);
  assert.equal(await page.locator('#storage-target').getAttribute('readonly'), '');
  await page.locator('#storage-form button[type="submit"]').click();
  await page.locator('#storage-form-error', { hasText: '互不包含' }).waitFor();
  picked = null;
  await page.locator('[data-action="storage-pick"]').click();
  await page.waitForFunction(() => !document.querySelector('#storage-form button[type="submit"]').disabled);
  assert.equal(await page.locator('#storage-target').inputValue(), anchor);
  picked = target;
  await page.locator('[data-action="storage-pick"]').click();
  await page.waitForFunction(expected => document.querySelector('#storage-target').value === expected, target);
  for (const width of [1165, 600]) {
    await page.setViewportSize({ width, height: 892 });
    const box = await page.locator('#storage-form button[type="submit"]').boundingBox();
    assert.ok(box.y >= 0 && box.y + box.height <= 892);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(root, `directory-selected-${width}.png`), fullPage: true });
  }
  await page.setViewportSize({ width: 1165, height: 892 });
  await page.locator('#storage-form button[type="submit"]').click();
  await page.locator('[data-cancel]').click();
  assert.equal(app.service.storage.status().pending, null);
  const schedule = async (mode = 'migrate') => {
    picked = target;
    await page.locator(`[data-mode="${mode}"]`).click();
    await page.locator('#storage-form button[type="submit"]').click();
    await page.locator('[data-confirm]').click();
    await page.locator('#storage-pending').waitFor();
  };
  await schedule();
  assert.equal(app.service.store.directory, anchor);
  await page.screenshot({ path: path.join(root, 'pending-1165.png'), fullPage: true });
  await page.locator('[data-action="storage-cancel"]').click();
  await page.locator('[data-mode="migrate"]').waitFor();
  await page.locator('[data-nav="notes"]').click();
  await page.locator(`[data-record="${note.id}"]`).click();
  await page.locator('.tiptap').fill('还没有保存的编辑');
  await page.locator('[data-nav="settings"]').click();
  await page.locator('[data-mode="migrate"]').click();
  await page.locator('#toast', { hasText: '未保存的笔记' }).waitFor();
  assert.equal(app.service.storage.status().pending, null);
  await page.locator('.work-tab').click();
  await page.locator('[data-action="save"]').click();
  await page.locator('#save-state', { hasText: '已本地保存' }).waitFor();
  await page.locator('[data-nav="settings"]').click();
  await schedule('select');
  assert.equal(app.service.storage.status().pending.mode, 'migrate');
  await page.close(); await app.close();
  app = await createServer({ directory: anchor, port: 0, chooseDirectory });
  const restored = await browser.newPage({ viewport: { width: 1165, height: 892 } });
  restored.on('pageerror', error => errors.push(error.message));
  await restored.goto(app.url);
  await restored.locator('[data-nav="settings"]').click();
  assert.equal(await restored.locator('#storage-current').inputValue(), target);
  assert.equal(path.dirname(app.service.state().libraries[0].localDirectory), target);
  assert.equal(app.service.store.get(note.id).data.content.includes('还没有保存的编辑'), true);
  await restored.screenshot({ path: path.join(root, 'migrated-1165.png'), fullPage: true });
  const other = new Service(path.join(base, 'other'));
  other.store.saveLibrary({ title: '另一套资料' }); other.close();
  picked = path.join(base, 'other');
  await restored.locator('[data-mode="select"]').click();
  await restored.locator('#storage-form button[type="submit"]').click();
  await restored.locator('#modal h2', { hasText: '切换到已有工作区' }).waitFor();
  await restored.locator('[data-cancel]').click();
  assert.equal(app.service.storage.status().pending, null);
  assert.equal(app.service.store.directory, target);
  await restored.locator('[data-mode="open"]').click();
  await restored.locator('#storage-target').waitFor();
  assert.equal(await restored.locator('#storage-target').inputValue(), picked);
  await restored.locator('[data-modal-close]').click();
  await restored.locator('.nav-item[data-nav="sync"]').click();
  picked = path.join(base, 'sync');
  await restored.locator('[data-action="choose-sync-folder"]').click();
  await restored.waitForFunction(expected => document.querySelector('#sync-folder').value === expected, picked);
  assert.equal(await restored.locator('[data-nav="backup"]').count(), 0);
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(root, 'report.json'), JSON.stringify({ passed: true, errors, pickerCalls,
    checks: ['current path', 'responsive layout and bottom access', 'unsaved preferences and notes', 'validation', 'picker cancellation and failure', 'reselection', 'sync picker and retired backup entry', 'restart migration and persistence'] }, null, 2));
  console.log('PASS: local storage settings, guards, cancellation and restart migration.');
} finally { await browser?.close(); await app.close(); }
